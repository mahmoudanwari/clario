#!/usr/bin/env node
/**
 * Generates docs/image-assets.md from the single source of truth in
 * src/data/images.ts, and reports which slots already have a real file in
 * src/assets/clario/.
 *
 * Usage: npm run manifest
 */
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { images } from '../src/data/images.ts';

const ASSET_DIR = 'src/assets/clario';
const EXT = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

async function filesIn(dir) {
  try {
    return (await readdir(dir))
      .filter((f) => EXT.some((e) => f.toLowerCase().endsWith(e)))
      .map((f) => f.replace(/\.[^.]+$/, ''));
  } catch {
    return [];
  }
}

// The OG image lives in public/ (social platforms can't read optimised assets),
// everything else goes through the Astro image pipeline in src/assets/.
const present = [...(await filesIn(ASSET_DIR)), ...(await filesIn('public/images/clario'))];

const supplied = images.filter((i) => present.includes(i.file));
const pending = images.filter((i) => !present.includes(i.file));
const byPriority = (p) => pending.filter((i) => i.priority === p);

const row = (img) => {
  const have = present.includes(img.file);
  return `| ${img.id} | ${img.page} | ${img.section} | ${img.aspect} | ${img.priority} | ${have ? '✅ supplied' : '⬜ needed'} |`;
};

const detail = (img) => `
### ${img.id} — \`${img.file}\`

${present.includes(img.file) ? '**Status:** ✅ supplied' : '**Status:** ⬜ still needed'}

| Field | Value |
| --- | --- |
| **Page** | ${img.page} |
| **Section** | ${img.section} |
| **Aspect ratio** | ${img.aspect} |
| **Suggested size** | ${img.size} |
| **Priority** | ${img.priority} |
| **People visible** | ${img.people} |
| **Uniform** | ${img.uniform} |
${img.focus ? `| **Crop focus** | \`object-position: ${img.focus}\` |\n` : ''}
**Subject.** ${img.subject}

**Composition.** ${img.composition}

**Camera.** ${img.camera}

**Lighting.** ${img.lighting}

**Colour grade.** ${img.colors}

**Background.** ${img.background}

**Alt text**
- EN — ${img.alt.en}
- NL — ${img.alt.nl}
- FR — ${img.alt.fr}
${img.notes ? `\n**Notes.** ${img.notes}\n` : ''}`;

const doc = `# Clario Cleaning — image asset manifest

> Generated by \`npm run manifest\` from \`src/data/images.ts\`. Do not edit by hand —
> edit the registry and regenerate.

## How to supply a finished image

1. Name the file exactly as the **asset filename** below, keeping your own extension
   (\`.jpg\`, \`.png\`, \`.webp\` or \`.avif\`). Example: \`home-hero-team-office.jpg\`.
2. Drop it into \`src/assets/clario/\`.
3. Run \`npm run build\`.

That is all. The \`<Media>\` component detects the file at build time, replaces the
placeholder, and generates responsive, optimised WebP automatically. No code change
is needed and the layout does not shift, because every placeholder already reserves
the final aspect ratio.

The social sharing image is the one exception: it must be a real file at
\`public/images/clario/og-default.png\` (or \`.jpg\`, with the path updated in
\`src/components/Seo.astro\`), because social platforms cannot read optimised or
inlined assets.

## Art direction (applies to every image)

- Professional commercial cleaning teams at work — calm, competent, unhurried.
- Modern Belgian-style commercial interiors: offices, shops, hospitality spaces.
- Natural daylight. No flash, no harsh shadows, no heavy vignettes.
- Warm, welcoming atmosphere; spaces clean but believably lived-in.
- Forest-green uniforms (#244F41 family) with a small ivory CLARIO wordmark.
- Realistic equipment: microfibre cloths, flat mops, refillable bottles, trolleys.
- Editorial grade: warm ivory highlights, muted greens, sand accents, low saturation.
- No readable third-party brands, no real business names, no identifiable logos.
- **Never** depict work at height (ladders, lifts, rope access) — the fictional
  company's scope deliberately excludes it.

## Status summary

- **Supplied:** ${supplied.length} / ${images.length}
- **Still needed:** ${pending.length} (P1: ${byPriority('P1').length}, P2: ${byPriority('P2').length}, P3: ${byPriority('P3').length})

## Priority order for the images still needed

${pending.length === 0 ? '_All slots are filled._' : ['P1', 'P2', 'P3']
  .map((p) => {
    const list = byPriority(p);
    if (!list.length) return '';
    const label = { P1: 'P1 — do these first (hero and key section images)', P2: 'P2 — important supporting images', P3: 'P3 — nice to have' }[p];
    return `### ${label}\n\n${list.map((i, n) => `${n + 1}. **${i.id}** \`${i.file}\` — ${i.page} / ${i.section}`).join('\n')}`;
  })
  .filter(Boolean)
  .join('\n\n')}

## All assets at a glance

| ID | Page | Section | Aspect | Priority | Status |
| --- | --- | --- | --- | --- | --- |
${images.map(row).join('\n')}

## Full specifications

${images.map(detail).join('\n---\n')}
`;

await mkdir('docs', { recursive: true });
await writeFile('docs/image-assets.md', doc, 'utf8');
console.log(`docs/image-assets.md written — ${supplied.length} supplied, ${pending.length} pending.`);
if (pending.length) {
  console.log('\nStill needed, in priority order:');
  for (const p of ['P1', 'P2', 'P3']) {
    for (const img of byPriority(p)) console.log(`  ${p}  ${img.id}  ${img.file}  (${img.page} / ${img.section})`);
  }
}
