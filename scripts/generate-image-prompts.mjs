#!/usr/bin/env node
/**
 * Generates docs/image-prompts.md — ready-to-paste prompts for every image
 * slot that does not yet have a file, built from the same registry that
 * drives the site (src/data/images.ts).
 *
 * The prompts are written as *continuation* requests, to be pasted into the
 * same ChatGPT conversation that produced the first batch, so the new images
 * inherit the established look rather than re-deriving it.
 *
 * Usage: npm run prompts
 */
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { images } from '../src/data/images.ts';

const EXT = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

async function filesIn(dir) {
  try {
    return (await readdir(dir))
      .filter((f) => EXT.some((e) => f.toLowerCase().endsWith(e)))
      .map((f) => f.replace(/\.[^.]+$/, ''));
  } catch {
    return [];
  }
}

const present = [...(await filesIn('src/assets/clario')), ...(await filesIn('public/images/clario'))];
const supplied = images.filter((i) => present.includes(i.file));
const needsRedo = (i) => typeof i.notes === 'string' && i.notes.startsWith('NEEDS REPLACEMENT');
const pending = images.filter((i) => !present.includes(i.file) || needsRedo(i));
const byPriority = (p) => pending.filter((i) => i.priority === p);

/** Repeated in full at the top of every prompt, so each one stands completely alone. */
const STYLE = [
  'Photorealistic editorial photograph for a commercial cleaning brand called Clario Cleaning, set in Belgium. Shot on a full-frame camera.',
  'Natural daylight only — no flash, no harsh shadows, no heavy vignette. Warm, calm, premium magazine feel.',
  'Colour grade: warm ivory highlights, muted forest and sage greens, subtle sand and oak accents, low saturation.',
  'Setting: a modern Belgian commercial interior — office, shop or hospitality space. Clean but believably lived-in, never sterile or staged.',
  'Any cleaning staff wear plain forest-green (#244F41 family) polos or work jackets with at most a small ivory CLARIO wordmark on the chest, and charcoal trousers. They look competent and unhurried, working rather than posing at the camera. Faces are often turned, in profile, or softly out of focus.',
  'Equipment is realistic: microfibre cloths, flat mops, refillable spray bottles, tidy trolleys.',
].join(' ');

const RULES = [
  'No text, letters, numbers, captions, labels or watermarks anywhere in the image. (The first batch came back with "Before Cleaning" burned in — the website adds its own labels in three languages, so any text in the image has to be cropped out.)',
  'No readable brand names or third-party logos on products, packaging, signage or screens.',
  'Uniforms stay exactly as established: plain forest green, at most a small ivory "CLARIO" wordmark on the chest.',
  'Never show work at height — no ladders, scaffolding, lifts or rope access. Everything reachable from the floor.',
  'No medical or hospital cues: no hazmat suits, no face masks, no clinical rooms.',
];

/** Written as a continuation of the existing conversation. */
const prompt = (img) => {
  const lines = [
    STYLE,
  ];
  if (needsRedo(img)) {
    lines.push(
      '',
      'WHY THIS IMAGE IS BEING REDONE: ' + img.notes.replace(/^NEEDS REPLACEMENT:s*/, '') + ' Please make sure the new version does not repeat it.'
    );
  }
  lines.push(
    '',
    `SUBJECT: ${img.subject}`,
    '',
    `COMPOSITION: ${img.composition}`,
    '',
    `CAMERA: ${img.camera}`,
    '',
    `LIGHTING: ${img.lighting.replace(/\.$/, '')}.`,
    '',
    `BACKGROUND: ${img.background}`,
    '',
    `PEOPLE: ${img.people}`
  );
  if (img.uniform !== 'Not applicable') lines.push('', `UNIFORM: ${img.uniform}`);
  lines.push(
    '',
    `ASPECT RATIO: ${img.aspect}, exported at ${img.size}.`,
    '',
    'MUST NOT INCLUDE:',
    ...RULES.map((r) => `- ${r}`)
  );
  return lines.join('\n');
};

const section = (img) => `
## ${img.id} — \`${img.file}\`

**${img.page} · ${img.section}** · priority ${img.priority} · aspect ${img.aspect} · ${img.size}
${img.notes ? `\n> ${img.notes}\n` : ''}
\`\`\`text
${prompt(img)}
\`\`\`

**Save as** \`${img.file}.png\` (or .jpg/.webp) in ${
  img.id === 'CL-30' ? '`public/images/clario/` — this one only' : '`src/assets/clario/`'
}.

<details><summary>Alt text already written for this slot — you don't need to supply any</summary>

- EN — ${img.alt.en}
- NL — ${img.alt.nl}
- FR — ${img.alt.fr}

</details>
`;

const allDone = `# Image prompts for ChatGPT

> Generated by \`npm run prompts\` from \`src/data/images.ts\`.

**Every one of the ${images.length} image slots has been supplied — there is nothing left to generate.**

If you add a new slot to \`src/data/images.ts\`, or delete a file from
\`src/assets/clario/\`, run \`npm run prompts\` again and a ready-to-paste prompt for it
will appear here.

## If you ever regenerate the before/after pair

CL-06 and CL-07 must be produced **as one scene in two states**: identical room, identical
camera position, identical lens, identical light — only the mess changes. The reliable way is
to generate the clean "after" frame first, then ask ChatGPT to *edit that same image* to add
believable end-of-day mess, rather than generating two images separately. Any shift in angle
is immediately visible when the slider moves, and would misrepresent a cleaning result.

Both images must also contain **no text** — the site renders its own Before/After labels in
three languages. The first version had "Before Cleaning" burned in and had to be cropped.
`;

const doc = pending.length === 0 ? allDone : `# Image prompts for ChatGPT — ${pending.length} image${pending.length === 1 ? "" : "s"} to generate

> Generated by \`npm run prompts\` from \`src/data/images.ts\`. Slots you have supplied drop
> out automatically, so regenerate after adding images.

Each prompt below is **completely self-contained** — it restates the house style in full, so
it works in a brand-new ChatGPT conversation with no prior context.

## Attach reference images — this matters more than the words

ChatGPT cannot remember the photographs it made for this brand. Written style notes get you
close, but attaching real examples gets you much closer. **Before pasting a prompt, attach two
or three of the existing images to the conversation** and say:

\`\`\`text
Here are photographs from an existing set for this brand. Match their lighting, colour grade,
uniforms and overall feel exactly in the image I am about to describe.
\`\`\`

Good reference images to attach, from \`src/assets/clario/\`:

- \`home-hero-team-office.jpg\` — the flagship shot: uniforms, daylight, office setting
- \`service-deep-detail-highreach.jpg\` — correct working posture, and the right level of detail
- \`sustainability-hero-materials.jpg\` — the still-life treatment and colour grade

## Then paste the prompt, one per message

Name each file exactly as its slot says, drop it into \`src/assets/clario/\`, and run
\`npm run build\`. The placeholder is replaced automatically — no code change, no layout
shift, and responsive WebP is generated for you. They can arrive one at a time.

**Status: ${supplied.length} of ${images.length} slots supplied, ${pending.length} to go.**

## Suggested order

${['P1', 'P2', 'P3']
  .map((p) => {
    const list = byPriority(p);
    if (!list.length) return '';
    const label = {
      P1: '**Do these first** — visible section images on the homepage',
      P2: '**Then these** — supporting detail images across the service and content pages',
      P3: '**Optional** — the placeholders are perfectly presentable until then',
    }[p];
    return `${label}:\n${list.map((i) => `- ${i.id} \`${i.file}\` — ${i.page} / ${i.section}`).join('\n')}`;
  })
  .filter(Boolean)
  .join('\n\n')}

---

${['P1', 'P2', 'P3']
  .map((p) => {
    const list = byPriority(p);
    if (!list.length) return '';
    return `# Priority ${p}\n${list.map(section).join('\n---\n')}`;
  })
  .filter(Boolean)
  .join('\n\n')}

---

## If you ever regenerate the before/after pair

CL-06 and CL-07 must be produced **as one scene in two states**: identical room, identical
camera position, identical lens, identical light — only the mess changes. The reliable way is
to generate the clean "after" frame first, then ask ChatGPT to *edit that same image* to add
believable end-of-day mess (cups, crumbs, smudges, chairs pushed out), rather than generating
two images separately. Any shift in angle is immediately visible when the slider moves, and
would misrepresent a cleaning result.
`;

await mkdir('docs', { recursive: true });
await writeFile('docs/image-prompts.md', doc, 'utf8');
console.log(
  `docs/image-prompts.md written — ${pending.length} prompts (P1: ${byPriority('P1').length}, P2: ${byPriority('P2').length}, P3: ${byPriority('P3').length}).`
);
