#!/usr/bin/env node
/**
 * Generates docs/image-prompts.md — ready-to-paste prompts for every image
 * slot that does not yet have a file, built from the same registry that
 * drives the site (src/data/images.ts).
 *
 * The prompts are written as *continuation* requests, to be pasted into the
 * same ChatGPT conversation that produced the first batch, so the new images
 * inherit the established look rather than re-deriving it.
 *
 * Usage: npm run prompts
 */
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { images } from '../src/data/images.ts';

const EXT = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

async function filesIn(dir) {
  try {
    return (await readdir(dir))
      .filter((f) => EXT.some((e) => f.toLowerCase().endsWith(e)))
      .map((f) => f.replace(/\.[^.]+$/, ''));
  } catch {
    return [];
  }
}

const present = [...(await filesIn('src/assets/clario')), ...(await filesIn('public/images/clario'))];
const supplied = images.filter((i) => present.includes(i.file));
const pending = images.filter((i) => !present.includes(i.file));
const byPriority = (p) => pending.filter((i) => i.priority === p);

const RULES = [
  'No text, letters, numbers, captions, labels or watermarks anywhere in the image. (The first batch came back with "Before Cleaning" burned in — the website adds its own labels in three languages, so any text in the image has to be cropped out.)',
  'No readable brand names or third-party logos on products, packaging, signage or screens.',
  'Uniforms stay exactly as established: plain forest green, at most a small ivory "CLARIO" wordmark on the chest.',
  'Never show work at height — no ladders, scaffolding, lifts or rope access. Everything reachable from the floor.',
  'No medical or hospital cues: no hazmat suits, no face masks, no clinical rooms.',
];

/** Written as a continuation of the existing conversation. */
const prompt = (img) => {
  const lines = [
    `Another image for the same Clario Cleaning set — keep the identical look to the photos you already made for this brand: same forest-green uniforms, same warm editorial colour grade, same natural daylight, same modern Belgian commercial interiors.`,
    '',
    `SUBJECT: ${img.subject}`,
    '',
    `COMPOSITION: ${img.composition}`,
    '',
    `CAMERA: ${img.camera}`,
    '',
    `LIGHTING: ${img.lighting}.`,
    '',
    `BACKGROUND: ${img.background}`,
    '',
    `PEOPLE: ${img.people}`,
  ];
  if (img.uniform !== 'Not applicable') lines.push('', `UNIFORM: ${img.uniform}`);
  lines.push(
    '',
    `ASPECT RATIO: ${img.aspect}, exported at ${img.size}.`,
    '',
    'MUST NOT INCLUDE:',
    ...RULES.map((r) => `- ${r}`)
  );
  return lines.join('\n');
};

const section = (img) => `
## ${img.id} — \`${img.file}\`

**${img.page} · ${img.section}** · priority ${img.priority} · aspect ${img.aspect} · ${img.size}
${img.notes ? `\n> ${img.notes}\n` : ''}
\`\`\`text
${prompt(img)}
\`\`\`

**Save as** \`${img.file}.png\` (or .jpg/.webp) in ${
  img.id === 'CL-30' ? '`public/images/clario/` — this one only' : '`src/assets/clario/`'
}.

<details><summary>Alt text already written for this slot — you don't need to supply any</summary>

- EN — ${img.alt.en}
- NL — ${img.alt.nl}
- FR — ${img.alt.fr}

</details>
`;

const doc = `# Image prompts for ChatGPT — the ${pending.length} slots still missing

> Generated by \`npm run prompts\` from \`src/data/images.ts\`. Slots you have supplied drop
> out automatically, so regenerate after adding images.

These are written to be pasted **into the same ChatGPT conversation that produced the first
batch**, so it can match the look it already established. If that conversation is gone, paste
the primer below first and it will re-establish the house style.

## Step 1 — paste this primer once (only if you're in a new conversation)

\`\`\`text
We're continuing a set of photographs for a fictional commercial cleaning brand called Clario
Cleaning, for a portfolio website set in Belgium. The established look across the set is:

- Photorealistic editorial photography, full-frame camera, natural daylight only — no flash,
  no harsh shadows, no heavy vignette.
- Warm, calm, premium magazine feel. Colour grade: warm ivory highlights, muted forest and
  sage greens, subtle sand and oak accents, low saturation.
- Modern Belgian commercial interiors — offices, shops, hospitality spaces. Clean but
  believably lived-in, never sterile or staged.
- Cleaning staff wear plain forest-green (#244F41 family) polos or work jackets with at most a
  small ivory "CLARIO" wordmark on the chest, charcoal trousers. They look competent and
  unhurried, working rather than posing at the camera. Faces are often turned, in profile, or
  softly out of focus — these are a fictional company's staff, so they should not read as
  portraits of identifiable people.
- Realistic equipment: microfibre cloths, flat mops, refillable spray bottles, tidy trolleys.
- Absolutely no text, labels or watermarks in the image, and no readable third-party brands.
- Never any work at height: no ladders, lifts or rope access.

The images already produced for this set are: a wide office hero with two cleaners at a
meeting table; a matched before/after pair of the same meeting room; four service images
(office workstations, a restaurant deep clean, a shopfront window clean, and wiping contact
points in a lobby); a showroom being mopped before opening; a sustainability still life of
reusable cloths and refillable bottles; a team of four in an office atrium; and a calm café
lounge. Match those.

I'll send the next images one at a time.
\`\`\`

## Step 2 — then paste the prompts below, one per message

Name each file exactly as its slot says, drop it into \`src/assets/clario/\`, and run
\`npm run build\`. The placeholder is replaced automatically — no code change, no layout
shift, and responsive WebP is generated for you. They can arrive one at a time.

**Status: ${supplied.length} of ${images.length} slots supplied, ${pending.length} to go.**

## Suggested order

${['P1', 'P2', 'P3']
  .map((p) => {
    const list = byPriority(p);
    if (!list.length) return '';
    const label = {
      P1: '**Do these first** — visible section images on the homepage',
      P2: '**Then these** — supporting detail images across the service and content pages',
      P3: '**Optional** — the placeholders are perfectly presentable until then',
    }[p];
    return `${label}:\n${list.map((i) => `- ${i.id} \`${i.file}\` — ${i.page} / ${i.section}`).join('\n')}`;
  })
  .filter(Boolean)
  .join('\n\n')}

---

${['P1', 'P2', 'P3']
  .map((p) => {
    const list = byPriority(p);
    if (!list.length) return '';
    return `# Priority ${p}\n${list.map(section).join('\n---\n')}`;
  })
  .filter(Boolean)
  .join('\n\n')}

---

## If you ever regenerate the before/after pair

CL-06 and CL-07 must be produced **as one scene in two states**: identical room, identical
camera position, identical lens, identical light — only the mess changes. The reliable way is
to generate the clean "after" frame first, then ask ChatGPT to *edit that same image* to add
believable end-of-day mess (cups, crumbs, smudges, chairs pushed out), rather than generating
two images separately. Any shift in angle is immediately visible when the slider moves, and
would misrepresent a cleaning result.
`;

await mkdir('docs', { recursive: true });
await writeFile('docs/image-prompts.md', doc, 'utf8');
console.log(
  `docs/image-prompts.md written — ${pending.length} prompts (P1: ${byPriority('P1').length}, P2: ${byPriority('P2').length}, P3: ${byPriority('P3').length}).`
);
